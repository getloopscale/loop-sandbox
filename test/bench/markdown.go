package main

import (
	"fmt"
	"sort"
	"strings"
)

// markdown renders the report as a page for the documentation.
func (r *Report) markdown() string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Benchmark: %s driver\n\n", r.Driver)
	b.WriteString("Generated by `make bench`. Do not edit by hand: run it again to replace the numbers.\n\n")
	fmt.Fprintf(&b, "Measured at %s through the REST API, with the image `%s`.\n", r.MeasuredAt, r.Image)
	b.WriteString("The numbers hold for this machine and this configuration. They are not a comparison with any other product.\n\n")

	b.WriteString("## Where it ran\n\n| Item | Value |\n| --- | --- |\n")
	if r.Host != nil {
		fmt.Fprintf(&b, "| CPU | %s |\n| Logical CPUs | %d |\n| Memory | %d MiB |\n| Kernel | %s |\n| Architecture | %s |\n",
			r.Host.CPUModel, r.Host.LogicalCPUs, r.Host.MemoryMiB, r.Host.Kernel, r.Host.Arch)
	} else {
		b.WriteString("| Host | not recorded: the API ran on another machine |\n")
	}
	keys := make([]string, 0, len(r.Versions))
	for k := range r.Versions {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(&b, "| %s | %s |\n", k, r.Versions[k])
	}

	b.WriteString("\n## Latency\n\nMilliseconds, measured by the client, one request at a time. Percentiles use the nearest rank.\n\n")
	b.WriteString("| Measurement | Samples | Min | p50 | p90 | Max | Mean |\n| --- | ---: | ---: | ---: | ---: | ---: | ---: |\n")
	for _, m := range r.Measurements {
		s := m.Summary
		fmt.Fprintf(&b, "| `%s` | %d | %.1f | %.1f | %.1f | %.1f | %.1f |\n", m.Name, s.Samples, s.MinMS, s.P50MS, s.P90MS, s.MaxMS, s.MeanMS)
	}
	b.WriteString("\nWhat each one times:\n\n")
	for _, m := range r.Measurements {
		fmt.Fprintf(&b, "- `%s`: %s.\n", m.Name, m.What)
	}
	if len(r.Skipped) > 0 {
		b.WriteString("\nNot measured:\n\n")
		for _, s := range r.Skipped {
			fmt.Fprintf(&b, "- `%s`: %s.\n", s.Name, s.Reason)
		}
	}

	if d := r.Density; d != nil {
		b.WriteString("\n## Density\n\n")
		fmt.Fprintf(&b, "%d sandboxes were alive at once, each after running a command. The run tried %d.\n", d.Reached, d.Target)
		if d.StoppedBy != "" {
			fmt.Fprintf(&b, "It stopped at this error: `%s`.\n", d.StoppedBy)
		} else {
			b.WriteString("It reached the target, so this is not the limit of the node.\n")
		}
		if d.MemoryPerSandboxMiB != nil {
			fmt.Fprintf(&b, "The host's available memory dropped by %.1f MiB for each sandbox, idle. Other processes on the host move this number.\n", *d.MemoryPerSandboxMiB)
		}
	}
	return b.String()
}
